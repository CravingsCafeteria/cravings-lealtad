create extension if not exists pgcrypto;

-- 1) TABLAS -------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text unique,
  full_name text not null default '',
  public_code uuid not null unique default gen_random_uuid(),
  role text not null default 'customer' check (role in ('customer','employee','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.wallets (
  customer_id uuid primary key references public.profiles(id) on delete cascade,
  stamps smallint not null default 0 check (stamps between 0 and 6),
  updated_at timestamptz not null default now()
);

create table if not exists public.purchases (
  id bigint generated by default as identity primary key,
  customer_id uuid not null references public.profiles(id) on delete cascade,
  amount numeric(10,2) not null check (amount >= 50),
  employee_id uuid not null references public.profiles(id),
  created_at timestamptz not null default now()
);

create table if not exists public.rewards (
  id bigint generated by default as identity primary key,
  customer_id uuid not null references public.profiles(id) on delete cascade,
  earned_from_purchase_id bigint unique references public.purchases(id) on delete set null,
  earned_at timestamptz not null default now(),
  redeemed_at timestamptz,
  redeemed_by uuid references public.profiles(id)
);

create index if not exists idx_purchases_customer_created on public.purchases(customer_id, created_at desc);
create index if not exists idx_rewards_customer_redeemed on public.rewards(customer_id, redeemed_at);

-- 2) CREAR PERFIL AUTOMÁTICAMENTE AL REGISTRARSE ------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, full_name)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data->>'full_name', '')
  )
  on conflict (id) do nothing;

  insert into public.wallets (customer_id)
  values (new.id)
  on conflict (customer_id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- 3) HELPERS DE SEGURIDAD ------------------------------------
create or replace function public.is_admin(p_uid uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = p_uid and p.role = 'admin'
  );
$$;

create or replace function public.is_staff(p_uid uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = p_uid and p.role in ('employee','admin')
  );
$$;


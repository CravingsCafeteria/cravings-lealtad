-- 5) EL EMPLEADO ESCANEA Y CONSULTA UNA TARJETA -------------
create or replace function public.lookup_customer(p_public_code uuid)
returns table (
  customer_id uuid,
  full_name text,
  stamps smallint,
  rewards_available bigint
)
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_staff(auth.uid()) then
    raise exception 'No tienes permiso de empleado.';
  end if;

  return query
  select p.id, p.full_name, w.stamps,
    (select count(*) from public.rewards r where r.customer_id = p.id and r.redeemed_at is null)
  from public.profiles p
  join public.wallets w on w.customer_id = p.id
  where p.public_code = p_public_code and p.role = 'customer';
end;
$$;

-- 6) REGISTRAR COMPRA MÍNIMA DE $50 --------------------------
create or replace function public.register_purchase(p_public_code uuid, p_amount numeric)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_customer public.profiles%rowtype;
  v_wallet public.wallets%rowtype;
  v_purchase_id bigint;
  v_new_stamps integer;
  v_reward_earned boolean := false;
  v_rewards_available bigint;
begin
  if not public.is_staff(auth.uid()) then
    raise exception 'No tienes permiso de empleado.';
  end if;
  if p_amount is null or p_amount < 50 then
    raise exception 'La compra mínima para sumar un sello es de $50 MXN.';
  end if;

  select * into v_customer from public.profiles
  where public_code = p_public_code and role = 'customer';
  if not found then raise exception 'Tarjeta no encontrada.'; end if;

  select * into v_wallet from public.wallets
  where customer_id = v_customer.id
  for update;

  insert into public.purchases(customer_id, amount, employee_id)
  values (v_customer.id, p_amount, auth.uid())
  returning id into v_purchase_id;

  v_new_stamps := v_wallet.stamps + 1;
  if v_new_stamps >= 7 then
    v_new_stamps := 0;
    v_reward_earned := true;
    insert into public.rewards(customer_id, earned_from_purchase_id)
    values (v_customer.id, v_purchase_id);
  end if;

  update public.wallets
  set stamps = v_new_stamps, updated_at = now()
  where customer_id = v_customer.id;

  select count(*) into v_rewards_available
  from public.rewards where customer_id = v_customer.id and redeemed_at is null;

  return jsonb_build_object(
    'customer_name', v_customer.full_name,
    'stamps', v_new_stamps,
    'reward_earned', v_reward_earned,
    'rewards_available', v_rewards_available
  );
end;
$$;

-- 7) CANJEAR BEBIDA GRATIS -----------------------------------
create or replace function public.redeem_reward(p_public_code uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_customer_id uuid;
  v_reward_id bigint;
begin
  if not public.is_staff(auth.uid()) then
    raise exception 'No tienes permiso de empleado.';
  end if;

  select id into v_customer_id from public.profiles
  where public_code = p_public_code and role = 'customer';
  if v_customer_id is null then raise exception 'Tarjeta no encontrada.'; end if;

  select id into v_reward_id
  from public.rewards
  where customer_id = v_customer_id and redeemed_at is null
  order by earned_at
  limit 1
  for update;

  if v_reward_id is null then raise exception 'Este cliente no tiene una bebida gratis disponible.'; end if;

  update public.rewards
  set redeemed_at = now(), redeemed_by = auth.uid()
  where id = v_reward_id;

  return jsonb_build_object('ok', true, 'reward_id', v_reward_id);
end;
$$;

-- 8) ADMIN: CAMBIAR ROL DE UNA CUENTA ------------------------
create or replace function public.admin_set_role(p_email text, p_role text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin(auth.uid()) then
    raise exception 'Sólo un administrador puede cambiar roles.';
  end if;
  if p_role not in ('customer','employee','admin') then
    raise exception 'Rol inválido.';
  end if;
  update public.profiles set role = p_role where lower(email) = lower(trim(p_email));
  if not found then raise exception 'No existe una cuenta con ese correo.'; end if;
end;
$$;

revoke all on function public.lookup_customer(uuid) from public;
